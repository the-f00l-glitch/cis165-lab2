#include <iostream>

int main() {
    // Variable declarations and initialization
    int num1 = 50;
    int num2 = 100;
    int total = 0;

    // Perform calculation before printing
    total = num1 + num2;

    // Display labelled output
    std::cout << "The sum of " << num1 << " and " << num2 << " is: " << total << std::endl;

    return 0;
}